"""
Express Bet API — pre-generated menu of accumulator bets.

All endpoints serve from DB (pre-generated by background job).
No real-time Fonbet API calls = no timeouts, no 500s.
"""
import logging
from typing import List, Optional

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.security import get_current_user
from app.core.database import get_db
from app.models.user import User

logger = logging.getLogger(__name__)
router = APIRouter()


# ---------------------------------------------------------------------------
# Lazy imports
# ---------------------------------------------------------------------------

def _get_generator():
    from app.services.express_generator import (
        get_menu_expresses,
        get_menu_express_by_preset,
        get_today_daily_express,
        get_user_expresses,
        get_available_leagues,
        generate_menu_batch,
    )
    return {
        "get_menu": get_menu_expresses,
        "get_preset": get_menu_express_by_preset,
        "get_today": get_today_daily_express,
        "get_user": get_user_expresses,
        "get_leagues": get_available_leagues,
        "generate_batch": generate_menu_batch,
    }


async def _get_user_from_token(current_user: dict, db: AsyncSession) -> User:
    user_id = current_user.get("user_id")
    if not user_id:
        raise HTTPException(status_code=401, detail="Invalid token")
    result = await db.execute(select(User).where(User.id == user_id))
    user = result.scalar_one_or_none()
    if not user:
        raise HTTPException(status_code=404, detail="User not found")
    return user


